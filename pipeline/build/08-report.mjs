/**
 * Step 8 — the documentation the brief requires.
 *
 *  - DATA_SOURCES.md (§4): every dataset with the exact license stated by the source at
 *    download time, its required attribution, and the script that produced the output.
 *  - out/08-review-records.md: 20 representative entries in readable form, which is what
 *    the §12 acceptance check ("20 representative entries resolve correctly") is read from.
 *
 * Run: node --max-old-space-size=6144 pipeline/build/08-report.mjs
 */
import fs from "node:fs";
import path from "node:path";
import { raw, out, repo, readJson, mb, step, done, PIPELINE_DIR } from "../lib/io.mjs";
import { allTenses, HABER_CONJUGATION_ID, SLOTS } from "../../src/lib/conjugation.js";

const started = step("08 · DATA_SOURCES.md and review records");

const { sources, datasetVersion } = readJson(path.join(PIPELINE_DIR, "sources.json"));
const manifest = readJson(raw("_manifest.json"));
const data = readJson(raw("_entries-final.json"));
const conjugations = readJson(raw("_conjugations.json"));
const pkg = readJson(out("07-package-report.json"));
const entries = data.entries;

// ---- DATA_SOURCES.md ------------------------------------------------------
const L = [];
L.push("# Data sources", "");
L.push("Every dataset bundled with or used to build Mi cuaderno's reference layer, with the exact license");
L.push("stated by the source at download time. Generated by `pipeline/build/08-report.mjs` — do not edit by hand.", "");
L.push(`Dataset version: **${datasetVersion}**  ·  Generated: ${new Date().toISOString().slice(0, 10)}`);
L.push(`Bundled size: **${mb(pkg.bytes.gzipTotal)} gzipped** across ${pkg.chunks} chunks · ` +
  `${pkg.counts.entries.toLocaleString()} entries · ${pkg.counts.conjugations.toLocaleString()} conjugation tables · ` +
  `${pkg.counts.examples.toLocaleString()} examples`, "");
L.push("> **Licensing note:** the app's own code is licensed separately from this data. The Jehle");
L.push("> conjugation database is **noncommercial** (CC BY-NC-SA 3.0); it must never be relicensed");
L.push("> together with the app code, and it rules out any commercial use of this app.", "");

for (const s of sources) {
  const d = manifest.downloads[s.key] || {};
  const recheck = manifest.rechecks?.[s.key];
  L.push(`## ${s.name}`, "");
  L.push(`- **Source URL:** ${s.url}`);
  L.push(`- **Landing page:** ${s.landingPage}`);
  L.push(`- **Downloaded:** ${d.downloadedAt || "—"} (${d.size || "—"}, sha256 \`${(d.sha256 || "").slice(0, 16)}…\`)`);
  L.push(`- **License:** ${s.license}`);
  L.push(`- **License text as stated by the source:** "${s.licenseQuote}" — verified at ${s.licenseVerifiedAt}`);
  L.push(`- **Required attribution:** ${s.attribution}`);
  if (s.provides) L.push(`- **Provides:** ${s.provides.join(", ")}`);
  if (s.upstream) L.push(`- **Upstream:** ${s.upstream}`);
  L.push(`- **Notes:** ${s.notes}`);
  if (recheck) {
    const state = recheck.error
      ? `could not reach the page (${recheck.error})`
      : recheck.patternPresent
        ? `still states "${recheck.expectPattern}"`
        : `no longer states "${recheck.expectPattern}" — re-read the page`;
    L.push(`- **Standing re-check** (${recheck.checkedAt?.slice(0, 10)}): ${state}`);
  }
  L.push("");
}

L.push("## Transformations applied", "");
L.push("| Step | Script | What it does |");
L.push("|---|---|---|");
L.push("| Download + provenance | `pipeline/build/01-download.mjs` | Fetches each source; records size, sha256 and download date; runs the standing source re-checks |");
L.push("| Index build | `pipeline/build/02-build-index.mjs` | Builds the form→lemma index from `forms[]` and `form_of` records; assigns canonical IDs; merges records sharing word+pos+etymology |");
L.push("| Frequency ranking | `pipeline/build/03-frequency.mjs` | Aggregates OpenSubtitles token counts into lemma ranks: citation-form-first, with ambiguous inflected tokens allocated in proportion to each candidate's unambiguous evidence |");
L.push("| Entry build | `pipeline/build/04-entries.mjs` | Builds DictEntry records for the top ~10k lemmas; sorts Mexico-labeled senses first; joins Jehle conjugations |");
L.push("| Examples | `pipeline/build/05-examples.mjs` | Attaches ≤3 Tatoeba es↔en pairs, each with sentence ID and contributor for both sides |");
L.push("| Conjugations | `pipeline/build/06-conjugate.mjs` | Extracts tables from kaikki's tagged forms for the verbs Jehle lacks; validates against Jehle cell by cell |");
L.push("| Packaging | `pipeline/build/07-package.mjs` | Compacts entries, builds the form and English indexes, splits into verified chunks under `public/dict/` |");
L.push("| Documentation | `pipeline/build/08-report.mjs` | Produces this file and the review records |");
L.push("");
L.push("## How attribution reaches the reader", "");
L.push("Every example sentence stores its Tatoeba sentence ID and contributor **for both the Spanish");
L.push("and the English side**, since each side is a separate contribution by a separate person. The");
L.push("license (`CC BY 2.0 FR`) and the URL template (`https://tatoeba.org/en/sentences/show/<id>`)");
L.push("are constants recorded once in the bundle manifest's attribution block rather than duplicated");
L.push("across all 56,420 sentence sides; the app renders ID, contributor, license and link on every");
L.push("example. The Ajustes screen shows the installed dataset version and this attribution.");
L.push("");
fs.writeFileSync(repo("DATA_SOURCES.md"), L.join("\n"), "utf8");

// ---- review records -------------------------------------------------------
/**
 * Chosen to cover exactly the cases §12 names: everyday vocabulary, several Mexico-flagged
 * terms, mixed parts of speech, verbs with conjugations, and entries with examples.
 */
const byLemma = (w) => entries.find((e) => e.lemma === w);
const MEXICO = (e) => e.senses.some((s) => s.regionLabels.includes("Mexico"));

const chosen = [];
const seen = new Set();
const add = (e) => {
  if (e && !seen.has(e.id)) { seen.add(e.id); chosen.push(e); }
};

for (const w of ["sacar", "tener", "casa", "año", "rápido", "madrugar", "haber"]) add(byLemma(w));
for (const e of entries.filter(MEXICO).slice(0, 8)) add(e);
for (const pos of ["noun", "adj", "adv", "verb", "intj", "pron", "prep"]) {
  add(entries.find((e) => e.pos === pos && e.examples.length && (e.freqRank ?? 1e9) < 900));
}
for (const e of entries.filter((e) => e.gender === "f" && e.examples.length).slice(0, 2)) add(e);

const haberTable = conjugations[HABER_CONJUGATION_ID];
const R = [];
R.push("# Phase 2 — generated records for review", "");
R.push(`${chosen.length} entries from the built dictionary, chosen to cover the cases brief §12 names:`);
R.push("everyday vocabulary, Mexico-flagged terms, mixed parts of speech, verbs with conjugations,");
R.push("and examples with their attribution.", "");
R.push(`Dataset version: \`${datasetVersion}\`  ·  ${entries.length.toLocaleString()} entries total`, "");
R.push("---", "");

for (const e of chosen) {
  R.push(`### ${e.lemma}  *(${e.pos}${e.gender ? `, ${e.gender}` : ""})*`, "");
  R.push(`- **ID:** \`${e.id}\``);
  R.push(`- **Frequency rank:** ${e.freqRank ?? "—"}`);
  R.push(`- **Searchable forms:** ${e.searchForms.length}${e.searchForms.length ? ` (e.g. ${e.searchForms.slice(0, 8).join(", ")}${e.searchForms.length > 8 ? ", …" : ""})` : ""}`);
  if (e.conjugationId) R.push(`- **Conjugation:** \`${e.conjugationId}\``);
  R.push("", "**Senses**", "");
  for (const s of e.senses.slice(0, 6)) {
    const marks = [...s.regionLabels, ...s.labels];
    R.push(`  ${marks.length ? `**[${marks.join(", ")}]** ` : ""}${s.gloss}`);
  }
  if (e.senses.length > 6) R.push(`  _…and ${e.senses.length - 6} more_`);
  R.push("");
  if (e.examples.length) {
    R.push("**Examples**", "");
    for (const x of e.examples) {
      R.push(`  - ${x.es}`);
      R.push(`    ${x.en}`);
      R.push(`    <sub>${x.sourceId} · ${x.contributor || "(no named contributor)"} · ${x.license} · ${x.sourceUrl}`);
      R.push(`    · English side ${x.englishSourceId} · ${x.englishContributor || "(no named contributor)"}</sub>`);
    }
    R.push("");
  }
  const table = conjugations[e.conjugationId];
  if (table) {
    const all = allTenses(table, haberTable);
    R.push(`**Conjugation** (source: ${table.source}; ustedes-first, vosotros last; ${Object.keys(all).length} tenses)`, "");
    for (const label of ["Indicative/Present", "Indicative/Preterite", "Indicative/Present Perfect"]) {
      const t = all[label];
      if (!t) continue;
      R.push(`  _${label}_ — ${SLOTS.map((s) => t[s] || "—").join(" · ")}`);
    }
    R.push("");
  }
  R.push("---", "");
}
fs.writeFileSync(out("08-review-records.md"), R.join("\n"), "utf8");

console.log(`  DATA_SOURCES.md          ${sources.length} datasets`);
console.log(`  out/08-review-records.md ${chosen.length} entries: ${chosen.slice(0, 10).map((e) => e.lemma).join(", ")}…`);
console.log(`  bundle                   ${mb(pkg.bytes.gzipTotal)} gzipped, ${pkg.chunks} chunks`);
done(started);
